from typing import Any, Dict, List, Optional
from ..config import settings
from ..schemas.common import PredictionStatus
from ..schemas.prediction import (
    LesionAnalysis,
    PredictionResponse,
    RecommendationResponse,
    TreatmentItem,
)
from ..services.inference_engine import ModelPrediction
from treatment_database.repository import TreatmentRepository


class TreatmentService:
    """
    Coordinates disease lookup, health score computation, Integrated Pest Management (IPM)
    recommendation assembly, and agricultural safety disclaimers across all supported crops.
    """

    def __init__(self, repository: Optional[TreatmentRepository] = None):
        self.repository = repository or TreatmentRepository(settings.TREATMENT_DB_DIR)

    def calculate_health_score(self, base_score: int, confidence: float, is_healthy: bool) -> int:
        if is_healthy:
            score = int(88 + (confidence * 10))
            return min(100, max(85, score))

        modulated = int(base_score - (confidence - 0.5) * 10)
        return min(80, max(10, modulated))

    def build_prediction_response(
        self,
        prediction: ModelPrediction,
        inference_time_ms: float = 0.0,
        forced_status: Optional[PredictionStatus] = None,
        language: Optional[str] = "en",
    ) -> PredictionResponse:
        lang = (language or "en").strip().lower()
        trans = self.repository.get_translation(lang) if lang != "en" else {}
        disclaimers = self.repository.disclaimers

        # Localize disclaimers
        t_disc = trans.get("disclaimers", {})
        general_disclaimer = t_disc.get(
            "general_disclaimer",
            disclaimers.get(
                "general_disclaimer",
                "This advisory is generated by PlantScan AI for preliminary screening. Consult local extension agronomists before field treatments.",
            ),
        )
        chemical_safety = t_disc.get(
            "chemical_safety_warning",
            disclaimers.get("chemical_safety_warning", ""),
        )
        uncertainty_notice = t_disc.get(
            "uncertainty_notice",
            disclaimers.get("uncertainty_notice", ""),
        )
        organic_guidance_note = t_disc.get(
            "organic_guidance_note",
            disclaimers.get("organic_guidance_note", ""),
        )

        t_crops = trans.get("crops", {})
        crop_display = t_crops.get(prediction.crop, prediction.crop)
        t_parts = trans.get("plant_parts", {})
        part_display = t_parts.get(prediction.plant_part, prediction.plant_part)
        t_diseases = trans.get("diseases", {})
        t_remedies = trans.get("remedies", {})
        t_apps = trans.get("applications", {})
        t_cautions = trans.get("caution_levels", {})
        t_summaries = trans.get("summaries", {})
        conf_pct = round(prediction.confidence * 100, 1)

        lesion_dto = None
        if prediction.lesion_measurement:
            lm = prediction.lesion_measurement
            lesion_dto = LesionAnalysis(
                lesion_detected=getattr(lm, "lesion_detected", False),
                lesion_count=getattr(lm, "lesion_count", 0),
                affected_area_percentage=getattr(lm, "affected_area_percentage", 0.0),
                leaf_area_pixels=getattr(lm, "leaf_area_pixels", 0),
                lesion_area_pixels=getattr(lm, "lesion_area_pixels", 0),
                severity_level=getattr(lm, "severity_level", "None (Healthy)"),
                bounding_boxes=getattr(lm, "bounding_boxes", []),
                overlay_image_base64=getattr(lm, "overlay_image_base64", None),
                mask_image_base64=getattr(lm, "mask_image_base64", None),
                method_note=getattr(lm, "method_note", "Experimental Computer Vision Morphological & Chromaticity Analysis"),
            )

        # 1. Handle Unsupported Plant Part Scenario (Stage 1 to Stage 2 Routing Gate)
        if prediction.predicted_class == "unsupported_part_disease":
            part_name = part_display or prediction.plant_part
            summary_text = (
                f"PlantScan AI Stage 1 identified plant anatomical tissue as '{part_name}'. "
                f"The current disease diagnostic models are calibrated specifically for foliar (leaf) and selected fruit pathologies. "
                f"Deep learning models for {part_name.lower()} vascular disorders and cankers are currently in development."
            )
            recommendation = RecommendationResponse(
                summary=summary_text,
                organic=[],
                chemical=[],
                prevention=[
                    f"Inspect the {part_name.lower()} closely for structural cracks, boring insect frass, bacterial oozing, or gummosis.",
                    "Sterilize pruning shears and tools with 70% isopropyl alcohol or 10% bleach solution between cuts to prevent pathogen transmission.",
                    "Avoid overhead irrigation to minimize moisture persistence on woody and stem tissue.",
                    "If foliar (leaf) symptoms are also present on the plant, submit a clear, well-lit photo of the affected leaf for foliar disease classification.",
                    "Consult a certified local agricultural extension officer or plant pathology clinic for definitive vascular diagnostics.",
                ],
                safety_notes=[
                    "CRITICAL SAFETY WARNING: Do NOT apply synthetic chemical fungicides or pesticides to stems or bark without laboratory diagnostic confirmation."
                ],
                photo_guidance=[
                    "Submit a close-up photo of the crop's leaves in diffuse natural daylight for leaf disease diagnosis.",
                    "Ensure the image is sharp, in-focus, and free of direct sun glare.",
                ],
                disclaimer=general_disclaimer,
                sources=["PlantScan AI Diagnostic Protocol", "ICAR/FAO Integrated Pest Management Guidelines"],
            )
            return PredictionResponse(
                status=PredictionStatus.UNSUPPORTED_PART_DISEASE,
                crop=crop_display,
                predicted_class="unsupported_part_disease",
                display_name=f"Unsupported Plant Part ({part_name})",
                confidence=prediction.confidence,
                is_healthy=False,
                plant_part=part_display,
                plant_part_confidence=getattr(prediction, "plant_part_confidence", None),
                plant_part_probabilities=getattr(prediction, "plant_part_probabilities", None),
                plant_health_score=50,
                recommendation=recommendation,
                lesion_analysis=lesion_dto,
                inference_time_ms=inference_time_ms,
                crop_detected_automatically=prediction.crop_detected_automatically,
                crop_confidence=getattr(prediction, "crop_confidence", None),
                candidate_crops=getattr(prediction, "candidate_crops", []),
                message=f"Plant part '{part_name}' is not currently supported for disease classification.",
            )

        # 2. Handle Unsupported Crop Scenario
        if prediction.predicted_class == "unsupported_crop":
            unknown_info = self.repository.default_unknown
            if "unsupported_crop" in t_summaries:
                summary_text = t_summaries["unsupported_crop"].format(crop=crop_display)
            else:
                summary_text = f"The provided crop '{prediction.crop}' is currently not in the PlantScan AI supported crop database."

            photo_tips = trans.get("photo_guidance", unknown_info.get("photo_guidance", []))
            prevention_tips = trans.get("prevention_measures", [
                f"Please submit images of supported crops ({', '.join(settings.SUPPORTED_CROPS)}).",
                "Contact local agricultural extension services for diagnostics on unsupported crop species.",
            ])
            msg = trans.get("status_messages", {}).get(
                "unsupported_crop",
                f"Crop '{prediction.crop}' is outside the current diagnostic scope.",
            )

            recommendation = RecommendationResponse(
                summary=summary_text,
                organic=[],
                chemical=[],
                prevention=prevention_tips,
                safety_notes=[
                    "Do not apply synthetic pesticides without certified confirmation of the target plant pathogen."
                ],
                photo_guidance=photo_tips,
                disclaimer=general_disclaimer,
                sources=unknown_info.get("sources", []),
            )
            return PredictionResponse(
                status=PredictionStatus.UNSUPPORTED_CROP,
                crop=crop_display,
                predicted_class="unsupported_crop",
                display_name=f"Unsupported Crop ({crop_display})",
                confidence=prediction.confidence,
                is_healthy=False,
                plant_part=part_display,
                plant_part_confidence=getattr(prediction, "plant_part_confidence", None),
                plant_part_probabilities=getattr(prediction, "plant_part_probabilities", None),
                plant_health_score=50,
                recommendation=recommendation,
                lesion_analysis=lesion_dto,
                inference_time_ms=inference_time_ms,
                crop_detected_automatically=prediction.crop_detected_automatically,
                crop_confidence=getattr(prediction, "crop_confidence", None),
                candidate_crops=getattr(prediction, "candidate_crops", []),
                message=msg,
            )

        # 2. Handle Low Confidence / Uncertain / Unknown / Uncertain Crop Scenario
        is_uncertain = (
            prediction.confidence < settings.CONFIDENCE_THRESHOLD
            or forced_status == PredictionStatus.UNCERTAIN
            or prediction.predicted_class == "uncertain_crop_detection"
        )

        if is_uncertain or prediction.predicted_class == "unknown":
            unknown_info = self.repository.default_unknown
            organic_items = [
                TreatmentItem(
                    name=item["name"],
                    method=item.get("method"),
                    application=item.get("application"),
                    frequency=item.get("frequency"),
                    caution_level="Low",
                )
                for item in unknown_info.get("organic_measures", [])
            ]

            safety_notes = [uncertainty_notice] if uncertainty_notice else []
            if chemical_safety:
                safety_notes.append(chemical_safety)

            if prediction.predicted_class == "uncertain_crop_detection":
                summary_text = (
                    f"Automated crop species identification is uncertain (suspected {crop_display} with {conf_pct}% confidence). "
                    "Please select your crop manually from the crop selector pills above to route to the target disease model."
                )
                msg = "Crop detection uncertain. Please confirm your crop species above to ensure accurate classification."
            elif "uncertain" in t_summaries:
                summary_text = t_summaries["uncertain"].format(confidence=conf_pct)
                msg = trans.get("status_messages", {}).get(
                    "uncertain",
                    "Low diagnostic certainty. Follow the photo tips to retake a clear photo in natural light.",
                )
            else:
                summary_text = (
                    f"Diagnostic confidence ({conf_pct}%) is below the {settings.CONFIDENCE_THRESHOLD*100:.0f}% threshold. "
                    "Visual symptoms are ambiguous. Do not apply chemical pesticides without physical verification."
                )
                msg = trans.get("status_messages", {}).get(
                    "uncertain",
                    "Low diagnostic certainty. Follow the photo tips to retake a clear photo in natural light.",
                )

            photo_tips = trans.get("photo_guidance", unknown_info.get("photo_guidance", []))
            prevention_tips = trans.get("prevention_measures", unknown_info.get("prevention_measures", []))

            recommendation = RecommendationResponse(
                summary=summary_text,
                organic=organic_items,
                chemical=[],
                prevention=prevention_tips,
                safety_notes=safety_notes,
                photo_guidance=photo_tips,
                disclaimer=general_disclaimer,
                sources=unknown_info.get("sources", []),
            )

            status = PredictionStatus.UNCERTAIN if is_uncertain else PredictionStatus.UNKNOWN
            predicted_display = t_diseases.get(
                prediction.predicted_class, prediction.display_name or "Uncertain Diagnosis"
            )

            return PredictionResponse(
                status=status,
                crop=crop_display,
                predicted_class=prediction.predicted_class,
                display_name=predicted_display,
                confidence=prediction.confidence,
                is_healthy=prediction.is_healthy,
                plant_part=part_display,
                plant_part_confidence=getattr(prediction, "plant_part_confidence", None),
                plant_part_probabilities=getattr(prediction, "plant_part_probabilities", None),
                plant_health_score=50,
                recommendation=recommendation,
                lesion_analysis=lesion_dto,
                inference_time_ms=inference_time_ms,
                crop_detected_automatically=prediction.crop_detected_automatically,
                crop_confidence=getattr(prediction, "crop_confidence", None),
                candidate_crops=getattr(prediction, "candidate_crops", []),
                message=msg,
            )

        # 3. Handle Confirmed Known Disease / Healthy Prediction
        treatment_data = self.repository.get_by_class(prediction.predicted_class)
        if not treatment_data:
            treatment_data = self.repository.get_by_crop_and_disease(prediction.crop, prediction.predicted_class)

        if not treatment_data:
            treatment_data = {
                "display_name": prediction.display_name or prediction.predicted_class.replace("_", " ").title(),
                "base_health_score": 90 if prediction.is_healthy else 50,
                "symptoms": "Diagnostic record present.",
                "organic_measures": [],
                "chemical_measures": [],
                "prevention_measures": ["Maintain general good crop hygiene."],
                "sources": ["PlantScan AI Knowledge Base"],
            }

        base_health = treatment_data.get("base_health_score", 90 if prediction.is_healthy else 45)
        health_score = self.calculate_health_score(base_health, prediction.confidence, prediction.is_healthy)

        organic_items = []
        for m in treatment_data.get("organic_measures", []):
            name_raw = m.get("name", "")
            t_rem = t_remedies.get(name_raw, {})
            app_raw = m.get("application", "")
            caut_raw = m.get("caution_level", "Low")
            organic_items.append(
                TreatmentItem(
                    name=t_rem.get("name", name_raw),
                    method=t_rem.get("method", m.get("method")),
                    application=t_rem.get("application", t_apps.get(app_raw, app_raw)),
                    frequency=t_rem.get("frequency", m.get("frequency")),
                    caution_level=t_cautions.get(caut_raw, caut_raw),
                )
            )

        chemical_items = []
        for c in treatment_data.get("chemical_measures", []):
            name_raw = c.get("name", "")
            t_rem = t_remedies.get(name_raw, {})
            caut_raw = c.get("caution_level", "Moderate")
            chemical_items.append(
                TreatmentItem(
                    name=t_rem.get("name", name_raw),
                    active_ingredient=c.get("active_ingredient"),
                    dosage=t_rem.get("dosage", c.get("dosage")),
                    safety_precautions=t_rem.get("safety_precautions", c.get("safety_precautions")),
                    caution_level=t_cautions.get(caut_raw, caut_raw),
                )
            )

        safety_notes: List[str] = []
        if chemical_items and chemical_safety:
            safety_notes.append(chemical_safety)
        if organic_guidance_note:
            safety_notes.append(organic_guidance_note)

        disease_display = t_diseases.get(
            prediction.predicted_class, treatment_data.get("display_name", prediction.display_name)
        )
        if prediction.is_healthy:
            if "healthy" in t_summaries:
                summary_text = t_summaries["healthy"].format(confidence=conf_pct)
            else:
                summary_text = f"Healthy plant detected with {conf_pct}% confidence."
        else:
            if "identified" in t_summaries:
                summary_text = t_summaries["identified"].format(disease=disease_display, confidence=conf_pct)
            else:
                summary_text = f"Identified {disease_display} with {conf_pct}% confidence."

        status_msg = trans.get("status_messages", {}).get("success", "Diagnosis completed successfully.")

        recommendation = RecommendationResponse(
            summary=summary_text,
            organic=organic_items,
            chemical=chemical_items,
            prevention=treatment_data.get("prevention_measures", []),
            safety_notes=safety_notes,
            disclaimer=general_disclaimer,
            sources=treatment_data.get("sources", []),
        )

        return PredictionResponse(
            status=PredictionStatus.SUCCESS,
            crop=crop_display,
            predicted_class=prediction.predicted_class,
            display_name=disease_display,
            confidence=prediction.confidence,
            is_healthy=prediction.is_healthy,
            plant_part=part_display,
            plant_part_confidence=getattr(prediction, "plant_part_confidence", None),
            plant_part_probabilities=getattr(prediction, "plant_part_probabilities", None),
            plant_health_score=health_score,
            recommendation=recommendation,
            lesion_analysis=lesion_dto,
            inference_time_ms=inference_time_ms,
            crop_detected_automatically=prediction.crop_detected_automatically,
            crop_confidence=getattr(prediction, "crop_confidence", None),
            candidate_crops=getattr(prediction, "candidate_crops", []),
            message=status_msg,
        )


_treatment_service_instance: Optional[TreatmentService] = None


def get_treatment_service() -> TreatmentService:
    global _treatment_service_instance
    if _treatment_service_instance is None:
        _treatment_service_instance = TreatmentService()
    return _treatment_service_instance
